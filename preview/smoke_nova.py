from pathlib import Path
import base64
from playwright.sync_api import sync_playwright

root = Path(__file__).resolve().parent
html=(root/'index.html').read_text().replace('<link rel="stylesheet" href="styles.css">','').replace('<script src="app.js"></script>','')
css=(root/'styles.css').read_text()
js=(root/'app.js').read_text()
data_uri='data:image/webp;base64,'+base64.b64encode((root/'assets/vehicle_scene.webp').read_bytes()).decode('ascii')
js=js.replace('assets/vehicle_scene.webp',data_uri)
checks=[]
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-web-security'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[]; requests=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.on('request',lambda req:requests.append(req.url))
 page.set_content(html)
 page.add_style_tag(content=css)
 page.add_script_tag(content=js)
 page.screenshot(path=str(root/'nova_desktop.png'),full_page=True)
 checks.append(('home',page.get_by_text('Salom, Aziza').count()>0))
 page.get_by_role('button',name='✓ Boraman').click()
 checks.append(('daily yes',page.get_by_text('Mos transport topildi').count()>0))
 page.locator('#bottomNav button').nth(2).click()
 page.get_by_text('Joyni tasdiqlash').click()
 checks.append(('rider confirm',page.get_by_text('Safarni boshlash').count()>0))
 page.get_by_role('button',name='◉ Xavfsiz chat').click()
 inp=page.locator('#chatMessage');inp.fill('+998901234567');page.get_by_label('Xabar yuborish').click()
 checks.append(('chat blocks number',page.get_by_text('Telefon, @username yoki havola').count()>0))
 inp.fill('Bekatda kutyapman');page.get_by_label('Xabar yuborish').click()
 checks.append(('chat permits normal message',page.get_by_text('Bekatda kutyapman').count()>0))
 page.locator('.back').click()
 page.locator('#bottomNav button').nth(0).click()
 page.get_by_text('Avtoparkni ko‘rish').click()
 checks.append(('fleet screen',page.get_by_text('Smart Avtopark').count()>0 and page.get_by_text('Electric').count()>0))
 page.get_by_label('Yo‘lovchilar soni').fill('18')
 checks.append(('group filter',page.get_by_text('18 KISHI').count()>0))
 page.locator('.chiprow button').filter(has_text='Avtobus').click()
 checks.append(('category filter',page.get_by_text('City Shuttle').count()>0))
 page.locator('.back').click()
 page.locator('#bottomNav button').nth(1).click()
 page.locator('#pickup').select_option(label='Kosonsoy bozori')
 page.get_by_role('button',name='Jadvalni saqlash').click()
 checks.append(('schedule edit',page.get_by_text('Kosonsoy bozori').count()>0))
 page.locator('#bottomNav button').nth(3).click()
 page.get_by_role('button',name='Haydovchi ilovasi').click()
 checks.append(('driver dashboard',page.get_by_text('Salom, Sherzod').count()>0))
 page.locator('#bottomNav button').nth(1).click()
 checks.append(('mixed vehicle offers',page.get_by_text('Sprinter').count()>0 and page.get_by_text('Cobalt').count()>0))
 page.get_by_role('button',name='Qabul qilish').first.click()
 checks.append(('accept offer',page.get_by_text('Olib ketish ro‘yxati').count()>0))
 page.get_by_text('Olib ketish ro‘yxati').first.click()
 page.get_by_text('Belgilash').first.click()
 checks.append(('pickup toggle',page.get_by_text('Olindi').count()>0))
 page.locator('.back').click()
 page.locator('#bottomNav button').nth(2).click()
 page.locator('.tiny-btn').filter(has_text='✎').last.click()
 page.locator('#priceValue').fill('17000')
 page.get_by_role('button',name='Saqlash').click()
 checks.append(('price updates',page.get_by_text('17 000 so‘m').count()>0))
 checks.append(('no runtime errors',not errors))
 checks.append(('no external network',not requests))
 mobile=browser.new_page(viewport={'width':390,'height':844})
 mobile.on('pageerror',lambda e:errors.append(str(e)))
 mobile.set_content(html)
 mobile.add_style_tag(content=css)
 mobile.add_script_tag(content=js)
 mobile.screenshot(path=str(root/'nova_mobile.png'),full_page=True)
 checks.append(('responsive phone',mobile.locator('.device').is_visible()))
 checks.append(('mobile has no runtime errors',not errors))
 browser.close()

print('\n'.join(('PASS' if ok else 'FAIL')+' '+name for name,ok in checks))
if errors: print('JS ERRORS', errors)
if requests: print('NETWORK',requests)
assert all(ok for _,ok in checks)
